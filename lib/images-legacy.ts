const BY_KEY = new Map(PHOTOS.map((p) => [p.key, p]));

export function photo(key: string): Photo {
  const p = BY_KEY.get(key);
  if (!p) throw new Error(`Unknown photo key: ${key}`);
  return p;
}

export const photosByGroup = (group: PhotoGroup) => PHOTOS.filter((p) => p.group === group);

/** URL passed to next/image (which resizes it). Moderate source size keeps fetches fast. */
export function img(key: string, width = 1600): string {
  const p = photo(key);
  return p.source === "unsplash"
    ? `${p.url}?w=${width}&q=80&fm=jpg&fit=max`
    : `${p.url}?auto=compress&cs=tinysrgb&w=${width}`;
}

export const imgAlt = (key: string): string => photo(key).alt;

/** A photo ready for <Img>: sized URL plus its alt text. */
export type Pic = { src: string; alt: string; key: string; pos?: string };
/** `pos` is a CSS object-position focal point, e.g. "50% 20%" (keeps faces in frame when cropped). */
export const pic = (key: string, width = 1400, pos?: string): Pic => ({
  src: img(key, width),
  alt: imgAlt(key),
  key,
  pos,
});

